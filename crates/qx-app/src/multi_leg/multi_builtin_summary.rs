use std::path::Path;

/// Facts used to project the stable composition summary for the independent-ledger builtin flow.
pub struct MultiBuiltinCompositionSummary<'a> {
    pub strategy_id: &'a str,
    pub strategy_kind: &'a str,
    pub quantity: i64,
    pub primary_instrument: &'a str,
    pub reference_instrument: &'a str,
    pub funding_bps: i64,
    pub risk_rule_set_version: &'a str,
    pub risk_source: &'a str,
    pub matching_kernel: &'a str,
    pub cost_source: &'a str,
    pub fill_model_name: &'a str,
    pub fill_model_source: &'a str,
    pub account_base_source: &'a str,
    pub primary_initial_cash_raw: i128,
    pub reference_initial_cash_raw: i128,
    pub primary_final_equity_raw: i128,
    pub reference_final_equity_raw: i128,
    pub primary_spec_path: Option<&'a Path>,
    pub reference_spec_path: Option<&'a Path>,
    pub attribution: &'a crate::MultiBuiltinAttribution,
}

/// Project verified multi-leg domain facts into the stable JSON summary shape.
pub fn multi_builtin_composition_summary_json(
    input: MultiBuiltinCompositionSummary<'_>,
) -> serde_json::Value {
    let MultiBuiltinCompositionSummary {
        strategy_id,
        strategy_kind,
        quantity,
        primary_instrument,
        reference_instrument,
        funding_bps,
        risk_rule_set_version,
        risk_source,
        matching_kernel,
        cost_source,
        fill_model_name,
        fill_model_source,
        account_base_source,
        primary_initial_cash_raw,
        reference_initial_cash_raw,
        primary_final_equity_raw,
        reference_final_equity_raw,
        primary_spec_path,
        reference_spec_path,
        attribution,
    } = input;
    serde_json::json!({
        "schema_version": 2,
        "strategy_id": strategy_id,
        "strategy": { "kind": strategy_kind, "quantity": quantity },
        "primary_instrument": primary_instrument,
        "reference_instrument": reference_instrument,
        "funding_bps": funding_bps,
        "risk_rules": {
            "rule_set_version": risk_rule_set_version,
            "source": risk_source,
            "matching_kernel": matching_kernel,
        },
        "execution_costs": { "source": cost_source },
        "market_specs": {
            "primary": primary_spec_path.map(|path| path.display().to_string()),
            "reference": reference_spec_path.map(|path| path.display().to_string()),
        },
        "margin_model": attribution.margin_model,
        "fill_model": { "name": fill_model_name, "source": fill_model_source },
        "accounts": {
            "account_base_source": account_base_source,
            "primary_initial_cash": primary_initial_cash_raw.to_string(),
            "reference_initial_cash": reference_initial_cash_raw.to_string(),
            "primary_final_equity_raw": primary_final_equity_raw.to_string(),
            "reference_final_equity_raw": reference_final_equity_raw.to_string(),
            "funding_rule": "2*quantity*leg-own-max-high + same-notional taker fee headroom, floor 100000",
        },
        "totals": {
            "turnover_raw": attribution.totals.1.to_string(),
            "fees_raw": attribution.totals.0.to_string(),
            "funding_raw": attribution.totals.2.to_string(),
            "filled_qty_raw": attribution.totals.3.to_string(),
            "margin_peak_raw": attribution.totals.4.to_string(),
            "net_cost_raw": attribution.net_cost_raw.to_string(),
            "cost_bps": attribution.cost_bps,
            "residual_filled_qty_raw": attribution.residual_filled_qty_raw.to_string(),
            "residual_fees_raw": attribution.residual_fees_raw.to_string(),
            "combined_return_bps": attribution.combined_return_bps,
        },
        "legs": attribution.leg_integrity.iter().map(crate::multi_leg_integrity_json).collect::<Vec<_>>(),
        "pending_reconcile": crate::multi_leg_pending_reconcile_json(&attribution.pending_reconcile),
        "groups": attribution.groups,
        "assumptions": [
            "fees=per-leg FIFO allocated to signal ts buckets",
            "margin=spec.initial_margin(|realized fills standing|, bar close, leverage=1), only on legs whose market spec declares a derivative product",
            "funding=realized-fill notional*funding_bps*holding_ms/(8h*10000), long pays positive, only on derivative legs; a leg without market spec is booked as spot multiplier 1 and is refused when funding_bps!=0",
            "cost_bps=net_cost*10000/turnover, null when turnover_raw=0 (no denominator: undefined, NOT zero cost)",
            "groups=paired by ts only when BOTH legs have realized fills; planned-but-unfilled qty is reported per leg, never paired",
            "pending_reconcile=a leg filled while its counterpart did not; no automatic close is executed",
            "fees=one explicit cost binding shared by both legs; market spec carries no maker/taker field, so per-venue fee tiers are not applied",
            "fill_model=one declared model shared by both legs; one_tick_slippage takes each leg's own spec price_tick",
        ],
    })
}
